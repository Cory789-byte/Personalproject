def add(n,d,c):
    m=re.fullmatch(r'(\d{4})-(\d{4})',c)
    if not m: return
    s,e=int(m.group(1))//100,int(m.group(2))//100
    h1=(24-s) if s>e else (e-s); h2=e if s>e else 0
    cd=d+dt.timedelta(days=1) if h2>h1 else d
    S[n]['shifts']+=1
    if cd in PH: S[n]['PH']+=1; w=2.5 if cd in EASTER else 1.5
